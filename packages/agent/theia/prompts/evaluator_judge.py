"""L3 LLM-as-Judge 评估 prompt 模板。"""

JUDGE_SYSTEM = """\
你是一位论文信息提取质量评审专家。你需要对比原文关键章节和从中提取的结构化信息，\
在 4 个维度上给出 0-1 的连续评分，并提供具体证据。

评分标准：
- 0.0-0.3: 差（大量错误/遗漏）
- 0.4-0.6: 中等（部分正确但有明显缺陷）
- 0.7-0.8: 良好（基本正确，少量遗漏）
- 0.9-1.0: 优秀（准确全面）

请仅以有效的 JSON 响应（不加 Markdown 围栏）。"""

JUDGE_PROMPT = """\
## 原文关键章节

{paper_context}

## 待评估的提取结果

```json
{extraction_json}
```

## 评估任务

请从以下 4 个维度评估提取质量，每个维度 0-1 分：

1. **faithfulness（忠实度）**: 提取的所有信息是否 100% 来自原文？
   - 检查：方法步骤是否真实、数字/数据集名称是否正确、有无编造内容
   - issues: 列出所有不忠实的具体实例

2. **coverage（关键信息覆盖）**: 原文最核心的创新点、方法、实验结果是否都被捕获？
   - 检查：核心创新是否被提取、关键实验数字是否包含、重要消融实验是否提及
   - missing: 列出被遗漏的重要信息

3. **insight（洞察质量）**: 提取内容的理解深度和表述质量
   - 检查：problem 是否精准、method 步骤是否逻辑清晰、contributions 是否有实质价值
   - notes: 对质量的整体评价

4. **video_ready（视频适配度）**: 信息是否足以支撑 2-3 分钟的论文解说视频？
   - 检查：步骤描述是否自包含（不需读原文就能理解）、是否有足够的可视化数据
   - notes: 改进建议

请以如下 JSON 格式输出：
{{
  "faithfulness": {{"score": 0.0, "issues": []}},
  "coverage": {{"score": 0.0, "missing": []}},
  "insight": {{"score": 0.0, "notes": ""}},
  "video_ready": {{"score": 0.0, "notes": ""}}
}}"""
